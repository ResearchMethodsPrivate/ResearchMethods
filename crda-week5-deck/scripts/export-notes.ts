/**
 * Writes docs/speaker-notes.md (rehearsal script + timing model) from
 * src/content/notes.ts, the speaking split in src/config/deck.config.ts and
 * the measured animation durations in src/content/motion.json.
 * Run: npm run notes
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { notes, type SlideNotes } from '../src/content/notes';
import { team } from '../src/config/deck.config';
import { TIMING, fmt, slideTimings } from '../src/content/timing';

const name = (id: string) => team.members.find((m) => m.id === id)?.name ?? id;
const rows = slideTimings().map((t, i) => ({
  ...t,
  i: i + 1,
  n: (notes as Record<string, SlideNotes>)[t.id],
  speakers: (team.speaking[t.id] ?? []).map(name).join(' + '),
}));

const sum = (k: 'target' | 'speech' | 'live') => rows.reduce((s, r) => s + r[k], 0);
const within = (t: number) => t >= 360 && t <= 480;

const perSpeaker = new Map<string, number>();
rows.forEach((r) => {
  const ids = team.speaking[r.id] ?? [];
  ids.forEach((m) => perSpeaker.set(name(m), (perSpeaker.get(name(m)) ?? 0) + r.live / ids.length));
});

const md = [
  '# Speaker notes — Week 5 interim presentation',
  '',
  'Presenters: **Anik**, **Alvi**, **Atul**. Generated by `npm run notes` from `src/content/notes.ts`; lines in **[brackets]** are click cues, not spoken.',
  '',
  '## Timing',
  '',
  `*Speech* = words at ${TIMING.wpm} wpm. *Live (model)* adds ${TIMING.transition}s per slide transition, ${TIMING.click}s per click, ${TIMING.handoff}s per speaker handoff, ${TIMING.introWait * 100}% of each measured intro animation and ${TIMING.stepWait * 100}% of each measured click animation (presenters talk over the rest). This is a model, **not** a rehearsal — time a full run with a stopwatch.`,
  '',
  '| # | Slide | Speaker | Target | Speech | Live (model) | Words |',
  '|---|-------|---------|-------:|-------:|-------------:|------:|',
  ...rows.map((r) => `| ${r.i} | ${r.n.title} | ${r.speakers} | ${r.target}s | ${Math.round(r.speech)}s | ${Math.round(r.live)}s${r.motionMeasured ? '' : '*'} | ${r.words} |`),
  `| | **Total** | | **${fmt(sum('target'))}** | **${fmt(sum('speech'))}** | **${fmt(sum('live'))}** | |`,
  '',
  rows.every((r) => r.motionMeasured) ? '' : '\\* animation time not yet measured — run `npm run qa:visual`.',
  '',
  `Brief: 6:00–8:00, aim ≈ 7:00. Modelled live total ${fmt(sum('live'))} → ${within(sum('live')) ? 'within range ✓' : 'OUT OF RANGE ✗'}.`,
  '',
  '**Approximate live time per person:** ' + [...perSpeaker].map(([k, v]) => `${k} ≈ ${Math.round(v)}s`).join(' · '),
  '',
  '## Stopwatch rehearsal log (fill in)',
  '',
  '| Date | Run | Anik | Alvi | Atul | Total | Notes |',
  '|------|-----|------|------|------|-------|-------|',
  '| | 1 | | | | | |',
  '| | 2 | | | | | |',
  '',
  '## Script',
  '',
  ...rows.flatMap((r) => [
    `### ${r.i}. ${r.n.title} — ${r.speakers} — target ${r.target}s`,
    '',
    ...r.n.lines.map((l) =>
      (l.startsWith('[') ? `**${l}**` : l).replace(/\{([ABC])\}/g, (_, m) => name(m)),
    ).flatMap((l) => [l, '']),
  ]),
].join('\n');

mkdirSync('docs', { recursive: true });
writeFileSync('docs/speaker-notes.md', md, 'utf8');
console.log(rows.map((r) => `${String(r.i).padStart(2)} ${r.n.title.padEnd(32)} target ${String(r.target).padStart(3)}s  speech ${String(Math.round(r.speech)).padStart(3)}s  live ${String(Math.round(r.live)).padStart(3)}s  (${r.words} w)`).join('\n'));
console.log(`TOTAL target ${fmt(sum('target'))} | speech ${fmt(sum('speech'))} | live model ${fmt(sum('live'))} | brief 6:00–8:00`);
console.log('Wrote docs/speaker-notes.md');
