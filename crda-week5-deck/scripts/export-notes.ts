/**
 * Writes docs/speaker-notes.md (rehearsal script + timing check) from
 * src/content/notes.ts and the speaking split in src/config/deck.config.ts.
 * Run: npm run notes
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { notes, spokenWords, WORDS_PER_MINUTE, type SlideNotes } from '../src/content/notes';
import { team } from '../src/config/deck.config';

const name = (id: string) => team.members.find((m) => m.id === id)?.name ?? id;
const fmt = (s: number) => `${Math.floor(s / 60)}:${String(Math.round(s % 60)).padStart(2, '0')}`;

const rows = Object.entries(notes as Record<string, SlideNotes>).map(([id, n], i) => {
  const words = spokenWords(n);
  const est = (words / WORDS_PER_MINUTE) * 60;
  return { i: i + 1, id, n, words, est, speakers: (team.speaking[id] ?? []).map(name).join(' + ') };
});

const target = rows.reduce((s, r) => s + r.n.seconds, 0);
const estimate = rows.reduce((s, r) => s + r.est, 0);
const within = (t: number) => t >= 360 && t <= 480;

const perSpeaker = new Map<string, number>();
rows.forEach((r) => {
  const ids = team.speaking[r.id] ?? [];
  ids.forEach((m) => perSpeaker.set(name(m), (perSpeaker.get(name(m)) ?? 0) + r.n.seconds / ids.length));
});

const md = [
  '# Speaker notes — Week 5 interim presentation',
  '',
  `Generated by \`npm run notes\` from \`src/content/notes.ts\`. Estimates assume ${WORDS_PER_MINUTE} words per minute; lines in **[brackets]** are click cues, not spoken.`,
  '',
  '## Timing check',
  '',
  '| # | Slide | Speaker | Target | Est. from words | Words |',
  '|---|-------|---------|-------:|----------------:|------:|',
  ...rows.map((r) => `| ${r.i} | ${r.n.title} | ${r.speakers} | ${r.n.seconds}s | ${Math.round(r.est)}s | ${r.words} |`),
  `| | **Total** | | **${fmt(target)}** | **${fmt(estimate)}** | |`,
  '',
  `Brief: 6:00–8:00. Target ${fmt(target)} → ${within(target) ? 'within range ✓' : 'OUT OF RANGE ✗'}; word-based estimate ${fmt(estimate)} → ${within(estimate) ? 'within range ✓' : 'OUT OF RANGE ✗'}.`,
  '',
  '**Approximate speaking time per person:** ' +
    [...perSpeaker].map(([k, v]) => `${k} ≈ ${Math.round(v)}s`).join(' · '),
  '',
  '## Script',
  '',
  ...rows.flatMap((r) => [
    `### ${r.i}. ${r.n.title} — ${r.speakers} — target ${r.n.seconds}s`,
    '',
    ...r.n.lines.map((l) =>
      (l.startsWith('[') ? `**${l}**` : l).replace(/\{([ABC])\}/g, (_, m) => name(m)),
    ).flatMap((l) => [l, '']),
  ]),
].join('\n');

mkdirSync('docs', { recursive: true });
writeFileSync('docs/speaker-notes.md', md, 'utf8');
console.log(rows.map((r) => `${String(r.i).padStart(2)} ${r.n.title.padEnd(32)} target ${String(r.n.seconds).padStart(3)}s  est ${String(Math.round(r.est)).padStart(3)}s`).join('\n'));
console.log(`TOTAL target ${fmt(target)} | estimate ${fmt(estimate)} | brief 6:00–8:00`);
console.log('Wrote docs/speaker-notes.md');
