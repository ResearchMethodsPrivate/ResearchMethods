import { gsap } from 'gsap';
import { scaleLinear } from 'd3-scale';
import { line, curveMonotoneX } from 'd3-shape';
import type { SlideDef } from '../lib/slide';
import { $, $$, gaussian, mulberry32, polyfit } from '../lib/util';

// Illustrative data-generating process (ours, not the paper's).
const truth = (x: number) => 0.55 * Math.sin(1.25 * x) + 0.32 * x;
const rand = mulberry32(11);
const sparse = Array.from({ length: 10 }, (_, i) => {
  const x = 0.35 + i * 0.6 + (rand() - 0.5) * 0.3;
  return { x, y: truth(x) + gaussian(rand) * 0.3 };
});
const dense = Array.from({ length: 150 }, () => {
  const x = 0.2 + rand() * 5.6;
  return { x, y: truth(x) + gaussian(rand) * 0.3 };
});
const fitSparse = polyfit(sparse.map((p) => p.x), sparse.map((p) => p.y), 5);
const fitDense = polyfit(dense.map((p) => p.x), dense.map((p) => p.y), 5);

const W = 1000, H = 640, M = { l: 70, r: 30, t: 30, b: 70 };
const sx = scaleLinear().domain([0, 6.1]).range([M.l, W - M.r]);
const sy = scaleLinear().domain([-0.9, 2.9]).range([H - M.b, M.t]);
const grid = Array.from({ length: 200 }, (_, i) => 0.25 + (i / 199) * 5.6);
const path = (f: (x: number) => number) =>
  line<number>().x((x) => sx(x)).y((x) => sy(Math.max(-0.9, Math.min(2.9, f(x))))).curve(curveMonotoneX)(grid) ?? '';

export const problemSlide: SlideDef = {
  id: 'problem',
  steps: 3,
  source: 'Problem framing: Mohebbi et al. (2026), §1 · Plot: illustrative synthetic data generated by us',
  html: () => `
    <header class="slide-head">
      <p class="kicker">01 — The problem</p>
      <h2>With only a little messy data, a model learns the wrong pattern</h2>
    </header>
    <div class="split split-40">
      <div class="col">
        <ul class="pill-list">
          <li><span class="pill-num">01</span> Only a few examples</li>
          <li><span class="pill-num">02</span> Getting more is expensive</li>
          <li><span class="pill-num">03</span> Measurements are noisy</li>
        </ul>
        <dl class="defs">
          <div class="def def-reg"><dt>Regression</dt><dd>Predicting a <em>number</em>, such as how much heating a building needs.</dd></div>
          <div class="def def-noise"><dt>Noise</dt><dd>Random errors in the measurements.</dd></div>
          <div class="def def-res"><dt>Residual</dt><dd>The gap: how far off the model’s guess was.</dd></div>
        </dl>
      </div>
      <figure class="plot plot-problem">
        <svg viewBox="0 0 ${W} ${H}" role="img" aria-label="Illustration: ten noisy points with a wiggly fitted curve and the gaps between them; a larger cloud shows the real trend.">
          <g class="axes">
            <line x1="${M.l}" y1="${H - M.b}" x2="${W - M.r}" y2="${H - M.b}" />
            <line x1="${M.l}" y1="${M.t}" x2="${M.l}" y2="${H - M.b}" />
            <text x="${W - M.r}" y="${H - M.b + 48}" text-anchor="end">input (for example: building size)</text>
            <text x="${M.l - 20}" y="${M.t + 6}" text-anchor="end" transform="rotate(-90 ${M.l - 20} ${M.t + 6})">result (for example: heating needed)</text>
          </g>
          <g class="dense">${dense.map((p) => `<circle cx="${sx(p.x)}" cy="${sy(p.y)}" r="4" />`).join('')}</g>
          <path class="fit-dense" d="${path(fitDense)}" />
          <g class="resid">${sparse.map((p) => `<line x1="${sx(p.x)}" x2="${sx(p.x)}" y1="${sy(p.y)}" y2="${sy(fitSparse(p.x))}" />`).join('')}</g>
          <path class="fit-sparse" d="${path(fitSparse)}" />
          <g class="sparse">${sparse.map((p) => `<circle cx="${sx(p.x)}" cy="${sy(p.y)}" r="9" />`).join('')}</g>
          <g class="plot-labels">
            <g class="lbl-sparse"><line x1="${M.l + 30}" x2="${M.l + 70}" y1="${M.t + 12}" y2="${M.t + 12}" /><text x="${M.l + 84}" y="${M.t + 20}">model learned from 10 examples</text></g>
            <text class="lbl-resid" x="${sx(sparse[3].x) + 16}" y="${(sy(sparse[3].y) + sy(fitSparse(sparse[3].x))) / 2 + 8}">gap (residual)</text>
            <g class="lbl-dense"><line x1="${M.l + 30}" x2="${M.l + 70}" y1="${M.t + 56}" y2="${M.t + 56}" /><text x="${M.l + 84}" y="${M.t + 64}">model learned from 150 examples</text></g>
          </g>
        </svg>
        <figcaption class="illus">Illustration with made-up points</figcaption>
      </figure>
    </div>`,
  build: (root) => {
    const tl = gsap.timeline({ paused: true });
    tl.fromTo($$(root, '.pill-list li'), { opacity: 0, x: -30 }, { opacity: 1, x: 0, stagger: 0.12, duration: 0.5, ease: 'power2.out' })
      .fromTo($(root, '.def-reg'), { opacity: 0 }, { opacity: 1, duration: 0.5 }, 0.3)
      .fromTo($(root, '.axes'), { opacity: 0 }, { opacity: 1, duration: 0.5 }, 0.2)
      .fromTo($$(root, '.sparse circle'), { opacity: 0, scale: 0, transformOrigin: '50% 50%' },
        { opacity: 1, scale: 1, stagger: 0.07, duration: 0.45, ease: 'back.out(2.2)' }, 0.5)
      .addLabel('s0')
      // Step 1 — fitted curve draws
      .fromTo($(root, '.fit-sparse'), { opacity: 1, drawSVG: '0%' }, { drawSVG: '100%', duration: 1.4, ease: 'power2.inOut' })
      .fromTo($(root, '.lbl-sparse'), { opacity: 0 }, { opacity: 1, duration: 0.4 }, '-=0.3')
      .addLabel('s1')
      // Step 2 — residuals drop from point to curve
      .fromTo($$(root, '.resid line'), { opacity: 1, drawSVG: '0%' }, { drawSVG: '100%', stagger: 0.06, duration: 0.5, ease: 'power1.out' })
      .fromTo([$(root, '.lbl-resid'), $(root, '.def-res')], { opacity: 0 }, { opacity: 1, duration: 0.5 }, '-=0.4')
      .addLabel('s2')
      // Step 3 — the data we can't collect
      .to($$(root, '.resid line'), { opacity: 0.25, duration: 0.4 })
      .fromTo($$(root, '.dense circle'), { opacity: 0 }, { opacity: 1, stagger: 0.006, duration: 0.3 }, '<')
      .fromTo($(root, '.fit-dense'), { opacity: 1, drawSVG: '0%' }, { drawSVG: '100%', duration: 1.2, ease: 'power2.inOut' }, '-=0.4')
      .fromTo($(root, '.lbl-dense'), { opacity: 0 }, { opacity: 1, duration: 0.4 }, '-=0.3')
      .addLabel('s3');
    return tl;
  },
};
